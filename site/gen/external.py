"""Copy the base defs BOR inherits from out of the game and Combat Extended.

The Pages build has no RimWorld install, so a BOR def whose ParentName lives in
vanilla, a DLC or CE would lose whatever that parent sets (a mechanitor
helmet's armor, a laser bullet's penetration...). This finds every such parent,
plus their own parents, and writes them to external_parents.xml, which the
build loads first. Run it where the game is installed, after a game or CE
update:

    python site/build.py --refresh-parents
"""
from __future__ import annotations

import re
from pathlib import Path

from lxml import etree

_PARSER = etree.XMLParser(remove_comments=True, remove_blank_text=True)
_DLCS = ("Royalty", "Ideology", "Biotech", "Anomaly", "Odyssey")
CE_PACKAGE_ID = "ceteam.combatextended"
CE_WORKSHOP_ID = "2890901044"


def _xml(base: Path):
    return sorted(base.rglob("*.xml")) if base.is_dir() else []


def find_ce(steamapps: Path) -> Path | None:
    """Combat Extended from the Mods folder or the Workshop; the official
    Workshop item wins when several copies are installed."""
    candidates = []
    for about in list((steamapps / "common" / "RimWorld" / "Mods").glob("*/About/About.xml")) + \
            list((steamapps / "workshop" / "content" / "294100").glob("*/About/About.xml")):
        try:
            text = about.read_text(encoding="utf-8-sig", errors="replace")
        except OSError:
            continue
        m = re.search(r"<packageId>\s*([^<\s]+)\s*</packageId>", text, re.I)
        if m and m.group(1).lower() == CE_PACKAGE_ID:
            candidates.append(about.parent.parent)
    candidates.sort(key=lambda p: p.name != CE_WORKSHOP_ID)
    return candidates[0] if candidates else None


def source_dirs(game: Path, ce: Path | None) -> list[tuple[str, Path]]:
    dirs = [("Core", game / "Data" / "Core" / "Defs")]
    dirs += [(dlc, game / "Data" / dlc / "Defs") for dlc in _DLCS]
    if ce is not None:
        dirs += [("Combat Extended", ce / "Defs")]
        dirs += [(f"Combat Extended {dlc}", ce / dlc / "Defs") for dlc in _DLCS]
    return [(label, d) for label, d in dirs if d.is_dir()]


def refresh(root: Path, game: Path, ce: Path | None, out: Path) -> tuple[int, list[str]]:
    """Write external_parents.xml. Returns (defs written, parent names still not found)."""
    bor_names: set[str] = set()
    wanted: set[str] = set()
    bor_dirs = [root / "Common"] + [p for p in (root / "Mods").iterdir() if p.is_dir()]
    for base in bor_dirs:
        for p in _xml(base):
            text = p.read_text(encoding="utf-8-sig", errors="replace")
            # Attributes only: skip XPath conditions like [@ParentName="..."] in patches.
            bor_names.update(re.findall(r'(?<![@\w])Name="([^"]+)"', text))
            wanted.update(re.findall(r'(?<![@\w])ParentName="([^"]+)"', text))

    index: dict[str, tuple[str, str, object]] = {}
    for label, d in source_dirs(game, ce):
        for p in _xml(d):
            try:
                tree = etree.parse(str(p), _PARSER)
            except etree.XMLSyntaxError:
                continue
            for el in tree.getroot():
                name = el.get("Name") if isinstance(el.tag, str) else None
                if name and name not in index:
                    index[name] = (label, p.relative_to(d).as_posix(), el)

    todo = sorted(wanted - bor_names)
    chosen: dict[str, tuple[str, str, object]] = {}
    missing: list[str] = []
    while todo:
        name = todo.pop()
        if name in chosen or name in bor_names:
            continue
        if name not in index:
            missing.append(name)
            continue
        chosen[name] = index[name]
        parent = index[name][2].get("ParentName")
        if parent:
            todo.append(parent)

    def comment(text: str):
        return etree.Comment(" " + text.replace("--", "- -").rstrip("-") + " ")  # XML comments can't hold "--"

    doc = etree.Element("Defs")
    doc.append(comment(
        "Generated by site/build.py (refresh-parents option). The vanilla, DLC and Combat Extended"
        " base defs that BOR inherits from, so the site build can resolve inheritance without the game."
        " Do not edit by hand."))
    for name in sorted(chosen, key=lambda n: (chosen[n][0], chosen[n][1], n)):
        label, rel, el = chosen[name]
        doc.append(comment(f"{label}: {rel}"))
        doc.append(el)
    out.write_bytes(etree.tostring(doc, xml_declaration=True, encoding="utf-8", pretty_print=True))
    return len(chosen), sorted(set(missing))
